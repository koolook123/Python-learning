# 【知识点】8 条

# 1. 字符串不可变：所有方法都返回新串。s.strip() 不写回给 s，等于什么都没做。
# 2. 去空白：strip() 两头都去，lstrip() / rstrip() 只去一边。
# 3. 切分：s.split(",") 按指定分隔符；s.split() 不带参数按任意空白切，并自动丢掉空串。
# 4. 拼接：",".join(列表)，列表里必须全是字符串，数字要先 str(x)。
# 5. 替换：s.replace(旧, 新)，默认全部替换；不支持按位置替换。
# 6. 判断：isdigit() 只认纯数字，带小数点、负号、逗号一律 False；配合 startswith / endswith / in。
# 7. f-string 对齐：{x:>8} 右对齐、{x:<8} 左对齐、{x:^8} 居中、{x:.2f} 两位小数、{x:0>3} 补零、{x:,} 千分位。
# 8. 切片：s[start:stop:step]；s[:3] 前三个，s[-3:] 后三个，s[::-1] 反转。

